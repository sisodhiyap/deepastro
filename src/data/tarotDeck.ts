/**
 * Deck Verification Helper
 * Verifies that the deck contains exactly 78 cards with 22 Major Arcana and 56 Minor Arcana.
 */
export const VERIFY_TAROT_DECK = () => {
  const total = TAROT_DECK.length;
  const major = TAROT_DECK.filter((c) => c.arcana === 'major').length;
  const minor = TAROT_DECK.filter((c) => c.arcana === 'minor').length;
  const wands = TAROT_DECK.filter((c) => c.suit === 'wands').length;
  const cups = TAROT_DECK.filter((c) => c.suit === 'cups').length;
  const swords = TAROT_DECK.filter((c) => c.suit === 'swords').length;
  const pentacles = TAROT_DECK.filter((c) => c.suit === 'pentacles').length;

  const uniqueIds = new Set(TAROT_DECK.map((c) => c.id));
  const hasDuplicates = uniqueIds.size !== total;

  return {
    valid: total === 78 && major === 22 && minor === 56 && !hasDuplicates,
    total,
    major,
    minor,
    suits: { wands, cups, swords, pentacles },
    uniqueIds: uniqueIds.size,
  };
};
