export const COUNTRIES = Array.from(new Set(WORLD_PLACES.map(p => p.country))).sort();

export function searchPlaces(query: string, countryFilter?: string): PlaceItem[] {
  const cleanQ = query.toLowerCase().trim();
  return WORLD_PLACES.filter(place => {
    if (countryFilter && countryFilter !== 'All Countries' && place.country !== countryFilter) {
      return false;
    }
    if (!cleanQ) return true;
    return (
      place.name.toLowerCase().includes(cleanQ) ||
      (place.state && place.state.toLowerCase().includes(cleanQ)) ||
      place.country.toLowerCase().includes(cleanQ)
    );
  });
}
